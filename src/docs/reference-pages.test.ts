import { describe, expect, it } from 'vitest'
import { keyBindingsPage, settingsPage } from './reference-pages'

// The lines of the page from the heading `from` up to the next heading, without blank lines.
function section (page: string, from: string) {
  const lines = page.split('\n')
  const start = lines.indexOf(from)
  if (start === -1) return []
  const end = lines.findIndex((line, index) => index > start && line.startsWith('#'))
  return lines.slice(start, end === -1 ? undefined : end).filter((line) => line !== '')
}

describe('the Settings page', () => {
  it('starts with a line saying it is generated by npm run docs, then its title, and ends with a newline', () => {
    const page = settingsPage({ properties: {} })
    const [generated, blank, title] = page.split('\n')

    expect(generated).toBe(
      "<!-- Generated by `npm run docs` from the config file's schema in src/core/config.ts. Don't edit this page by hand: change the source and run `npm run docs` again. -->"
    )
    expect([blank, title]).toEqual(['', '# Settings'])
    expect(page.endsWith('\n')).toBe(true)
  })

  it('lists a group under its name and description, and each of its settings by its dotted name', () => {
    const page = settingsPage({
      properties: {
        pane: {
          description: "Each Pane's look.",
          properties: {
            scrollBar: { description: 'Whether each Pane shows a scroll bar.', enum: ['none', 'visible'], default: 'none' },
          },
        },
      },
    })

    expect(section(page, '## `pane`')).toEqual(['## `pane`', "Each Pane's look."])
    expect(section(page, '### `pane.scrollBar`')).toEqual([
      '### `pane.scrollBar`',
      'Whether each Pane shows a scroll bar.',
      '- Values: `none`, `visible`',
      '- Default: `none`',
    ])
  })

  it('lists a setting in no group by its bare name, leaving out $schema, which is no setting', () => {
    const page = settingsPage({
      properties: {
        $schema: { type: 'string' },
        sessionBanner: { description: 'Whether cycling shows the Session Banner.', type: 'boolean', default: true },
      },
    })

    expect(page).not.toContain('$schema')
    expect(section(page, '## `sessionBanner`')).toEqual([
      '## `sessionBanner`',
      'Whether cycling shows the Session Banner.',
      '- Values: `true`, `false`',
      '- Default: `true`',
    ])
  })

  it("gives a whole number's range, and the words it takes besides", () => {
    const page = settingsPage({
      properties: {
        background: {
          description: 'Behind the terminal.',
          properties: {
            transparency: { description: 'How transparent.', type: 'integer', minimum: 0, maximum: 100, default: 25 },
          },
        },
        pane: {
          description: 'Panes.',
          properties: {
            scrollbackLines: {
              description: 'How many lines are kept.',
              default: 10000,
              oneOf: [{ type: 'integer', minimum: 0, maximum: 1000000 }, { const: 'unlimited' }],
            },
          },
        },
      },
    })

    expect(section(page, '### `background.transparency`')).toContain('- Values: a whole number from 0 to 100')
    expect(section(page, '### `pane.scrollbackLines`')).toEqual([
      '### `pane.scrollbackLines`',
      'How many lines are kept.',
      '- Values: a whole number from 0 to 1,000,000, or `unlimited`',
      '- Default: `10000`',
    ])
  })

  it('gives a text setting its examples, and says when a setting has no default', () => {
    const page = settingsPage({
      properties: {
        shell: {
          description: 'Shells.',
          properties: { program: { description: 'The program.', type: 'string' } },
        },
        theme: {
          description: "The Theme's name.",
          type: 'string',
          default: 'Default',
          examples: ['Default', 'Tokyo Night'],
        },
      },
    })

    expect(section(page, '### `shell.program`')).toEqual([
      '### `shell.program`',
      'The program.',
      "- Values: any text that isn't empty",
      '- Default: not set',
    ])
    expect(section(page, '## `theme`')).toEqual([
      '## `theme`',
      "The Theme's name.",
      "- Values: any text that isn't empty, such as `Default`, `Tokyo Night`",
      '- Default: `Default`',
    ])
  })

  it('points to the Key bindings page for keyBindings, rather than listing its actions', () => {
    const page = settingsPage({
      properties: {
        keyBindings: {
          description: 'How shortcuts are written.',
          type: 'object',
          properties: { newTab: { type: ['string', 'null'], default: 'Cmd+T' } },
        },
      },
    })

    expect(page).not.toContain('keyBindings.newTab')
    expect(section(page, '## `keyBindings`')).toEqual([
      '## `keyBindings`',
      "Each action's shortcut, listed with its default in [Key bindings](key-bindings.md).",
    ])
  })
})

describe('the Key bindings page', () => {
  const tableOf = (page: string) => page.split('\n').filter((line) => line.startsWith('|'))

  it('starts with a line saying it is generated by npm run docs, then explains rebinding in the config file', () => {
    const page = keyBindingsPage({
      defaults: {},
      paletteActionLabels: {},
      shortcutSyntax: 'Each action\'s shortcut, such as "Cmd+Shift+D".',
    })
    const [generated, blank, title] = page.split('\n')

    expect(generated).toBe(
      "<!-- Generated by `npm run docs` from defaultKeyBindings in src/core/key-bindings.ts and the Command Palette's titles in src/core/core.ts. Don't edit this page by hand: change the source and run `npm run docs` again. -->"
    )
    expect([blank, title]).toEqual(['', '# Key bindings'])
    expect(page).toContain('`keyBindings` in the [config file](config-file.md)')
    expect(page).toContain('Each action\'s shortcut, such as "Cmd+Shift+D".')
    expect(page.endsWith('\n')).toBe(true)
  })

  it('lists every action by its config name, with its Command Palette title where it has one, and its default', () => {
    const page = keyBindingsPage({
      defaults: { openCommandPalette: 'Cmd+K', newTab: 'Cmd+T', renameTab: null },
      paletteActionLabels: { newTab: 'New Tab', renameTab: 'Rename Tab' },
      shortcutSyntax: 'How shortcuts are written.',
    })

    expect(tableOf(page)).toEqual([
      '| Action | Command Palette | Default |',
      '| --- | --- | --- |',
      '| `openCommandPalette` |  | `Cmd+K` |',
      '| `newTab` | New Tab | `Cmd+T` |',
      '| `renameTab` | Rename Tab | unbound |',
    ])
  })

  it('writes a shortcut holding a backtick as code all the same', () => {
    const page = keyBindingsPage({ defaults: { nextSession: 'Cmd+`' }, paletteActionLabels: {}, shortcutSyntax: '' })

    expect(tableOf(page)).toContain('| `nextSession` |  | `` Cmd+` `` |')
  })
})
