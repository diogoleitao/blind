import { configSchema } from '../core/config'
import { paletteActionLabels } from '../core/core'
import { defaultKeyBindings } from '../core/key-bindings'

// What the Settings page reads of a setting's schema, or of a group's.
export interface SettingSchema {
  description?: string;
  type?: string | readonly string[];
  enum?: readonly unknown[];
  const?: unknown;
  minimum?: number;
  maximum?: number;
  oneOf?: readonly SettingSchema[];
  default?: unknown;
  examples?: readonly unknown[];
  properties?: Record<string, SettingSchema>;
}

// `value` as inline code. Code holding a backtick, such as Cmd+`, is fenced by two, with spaces Markdown strips.
function inlineCode (value: unknown) {
  const text = String(value)
  return text.includes('`') ? `\`\` ${text} \`\`` : `\`${text}\``
}

// The values a setting, or one of the alternatives it takes, allows, as a phrase.
function allowedValues (schema: SettingSchema): string {
  if (schema.oneOf) return schema.oneOf.map(allowedValues).join(', or ')
  if (schema.enum) return schema.enum.map(inlineCode).join(', ')
  if (schema.const !== undefined) return inlineCode(schema.const)
  if (schema.type === 'boolean') return [true, false].map(inlineCode).join(', ')
  if (schema.type === 'integer') {
    return `a whole number from ${schema.minimum?.toLocaleString('en-GB')} to ${schema.maximum?.toLocaleString('en-GB')}`
  }
  const examples = schema.examples ? `, such as ${schema.examples.map(inlineCode).join(', ')}` : ''
  return `any text that isn't empty${examples}`
}

// A setting under a heading of `level`, by `name`.
function settingSection (level: string, name: string, schema: SettingSchema) {
  return [
    `${level} ${inlineCode(name)}`,
    '',
    schema.description ?? '',
    '',
    `- Values: ${allowedValues(schema)}`,
    `- Default: ${schema.default === undefined ? 'not set' : inlineCode(schema.default)}`,
  ]
}

// A group under its name and description, then each of its settings by its dotted name.
function groupSection (name: string, schema: SettingSchema) {
  return [
    `## ${inlineCode(name)}`,
    '',
    schema.description ?? '',
    ...Object.entries(schema.properties ?? {}).flatMap(([key, setting]) => [
      '',
      ...settingSection('###', `${name}.${key}`, setting),
    ]),
  ]
}

// keyBindings' actions are listed on the Key bindings page, which explains how shortcuts are written.
function keyBindingsSection () {
  return [
    `## ${inlineCode('keyBindings')}`,
    '',
    "Each action's shortcut, listed with its default in [Key bindings](key-bindings.md).",
  ]
}

// A generated page: the line saying so, naming where it comes from, then its title and `sections`, ending with a newline.
function generatedPage (source: string, title: string, sections: string[][]) {
  const generated = `<!-- Generated by \`npm run docs\` from ${source}. Don't edit this page by hand: change the source and run \`npm run docs\` again. -->`
  return [[generated], [`# ${title}`], ...sections].map((lines) => lines.join('\n')).join('\n\n') + '\n'
}

// The Settings page: every setting in the config file's schema, under its group, or by its bare name for one in no
// group, after the `blind settings` command that changes them. Editors read `$schema`, so it's no setting.
export function settingsPage (schema: SettingSchema): string {
  const intro = [
    'Every setting the [config file](config-file.md) takes, in the order the file\'s schema lists them. A setting in a group is named by the group and the setting joined by a dot, such as `pane.scrollBar`, and one in no group, such as `theme`, by its name alone. A setting the file leaves out is at its default.',
    '',
    'From the terminal: [`blind settings`](../blind-command/settings.md) lists every setting but `keyBindings` and changes them as you go.',
  ]
  const sections = Object.entries(schema.properties ?? {})
    .filter(([name]) => name !== '$schema')
    .map(([name, setting]) => {
      if (name === 'keyBindings') return keyBindingsSection()
      return setting.properties ? groupSection(name, setting) : settingSection('##', name, setting)
    })
  return generatedPage("the config file's schema in src/core/config.ts", 'Settings', [intro, ...sections])
}

export interface KeyBindingsPageSource {
  // Each action's default shortcut, or null when it's unbound, in the order the page lists them.
  defaults: Record<string, string | null>;
  // The Command Palette's title of each action it offers.
  paletteActionLabels: Record<string, string>;
  // How a shortcut is written, as the config file's schema says.
  shortcutSyntax: string;
}

// The Key bindings page: how to rebind an action in the config file, then every action with its default shortcut.
export function keyBindingsPage ({ defaults, paletteActionLabels, shortcutSyntax }: KeyBindingsPageSource): string {
  const rebinding = [
    'Rebind an action under `keyBindings` in the [config file](config-file.md), by its name in the Action column below. This binds New Tab to Cmd+Shift+T and unbinds Hide Tab:',
    '',
    '```jsonc',
    '{',
    '  "keyBindings": {',
    '    "newTab": "Cmd+Shift+T",',
    '    "hideTab": null',
    '  }',
    '}',
    '```',
  ]
  const table = [
    '| Action | Command Palette | Default |',
    '| --- | --- | --- |',
    ...Object.entries(defaults).map(
      ([action, shortcut]) =>
        `| ${inlineCode(action)} | ${paletteActionLabels[action] ?? ''} | ${shortcut === null ? 'unbound' : inlineCode(shortcut)} |`
    ),
  ]
  return generatedPage(
    "defaultKeyBindings in src/core/key-bindings.ts and the Command Palette's titles in src/core/core.ts",
    'Key bindings',
    [rebinding, [shortcutSyntax], table]
  )
}

// Each generated page, by its path from the repository's root, as the app's settings and key bindings make it.
export function referencePages (): Record<string, string> {
  return {
    'docs/configuration/settings.md': settingsPage(configSchema),
    'docs/configuration/key-bindings.md': keyBindingsPage({
      defaults: defaultKeyBindings,
      paletteActionLabels,
      shortcutSyntax: configSchema.properties.keyBindings.description,
    }),
  }
}
